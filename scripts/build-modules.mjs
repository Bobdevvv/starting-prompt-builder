// Generates src/modules.data.ts from modules/*.md: the rules and the frame
// only. Prevents, Why, Sources and testing notes stay in the Markdown; they're
// for people choosing modules, not for the generated prompt.
//
//   node scripts/build-modules.mjs          write src/modules.data.ts
//   node scripts/build-modules.mjs --check  exit 1 if the file is out of date

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MODULES_DIR = join(REPO_ROOT, "modules");
const OUTPUT_PATH = join(REPO_ROOT, "src", "modules.data.ts");

// The order modules appear in a generated prompt.
export const MODULE_ORDER = [
  "core", "user-leads", "dependencies", "supply-chain", "secrets-strict", "local-machine", "git-workflow",
  "testing", "work-log", "code-clarity", "public-repo", "accessibility", "user-data",
  "deploy-ops", "budgets", "explain-as-you-go", "writing",
];

function parseModuleFile(text) {
  const normalisedText = text.replaceAll("\r\n", "\n");
  const frontmatter = normalisedText.match(/^---\n([\s\S]*?)\n---\n/)?.[1] ?? "";
  const field = (name) => frontmatter.match(new RegExp(`^${name}:\\s*(.*)$`, "m"))?.[1].trim() ?? "";
  const sections = {};
  const lines = normalisedText.split("\n");
  lines.forEach((line, index) => {
    if (!line.startsWith("## ")) return;
    const end = lines.findIndex((other, i) => i > index && other.startsWith("## "));
    sections[line.slice(3)] = lines.slice(index + 1, end < 0 ? undefined : end).join("\n").trim();
  });
  return { field, sections };
}

export function buildModuleData() {
  const modules = MODULE_ORDER.map((moduleId) => {
    const { field, sections } = parseModuleFile(readFileSync(join(MODULES_DIR, `${moduleId}.md`), "utf8"));
    const rules = Object.fromEntries(Object.entries(sections).filter(([heading]) => heading.startsWith("Rules")));
    const variantsField = field("variants");
    return {
      id: moduleId,
      title: moduleId === "core" ? "How we work" : field("title"),
      question: field("question"),
      targets: field("targets").split(",").map((target) => target.trim()).filter(Boolean),
      variants: variantsField ? variantsField.split(",").map((variant) => variant.trim()) : [],
      prevents: readPrevents(moduleId),
      rules,
    };
  });
  const frame = parseModuleFile(readFileSync(join(MODULES_DIR, "frame.md"), "utf8")).sections;
  return {
    modules,
    frame: {
      opening: frame.Opening,
      project: frame["The project"],
      firstReplyCode: frame["Your first reply"],
      firstReplyAgent: frame["Your first reply for other coding agents"],
      firstReplyBrowser: frame["Your first reply in the browser"],
    },
  };
}

// The one-line "Prevents" summary, shown in the builder next to each module.
function readPrevents(moduleId) {
  const text = readFileSync(join(MODULES_DIR, `${moduleId}.md`), "utf8").replaceAll("\r\n", "\n");
  const block = text.match(/\*\*Prevents:\*\*([\s\S]*?)(\n## |\n\n[^-\s])/)?.[1] ?? "";
  return block.replace(/\n-\s*/g, " ").replace(/\s+/g, " ").replace(/;\s*/g, "; ").trim();
}

export function renderModuleDataFile() {
  const data = buildModuleData();
  return [
    "// GENERATED by scripts/build-modules.mjs from modules/*.md. Do not edit by hand:",
    "// change the Markdown and run `npm run build:modules`.",
    "",
    "export interface ModuleData {",
    "  readonly id: string;",
    "  readonly title: string;",
    "  readonly question: string;",
    "  readonly targets: readonly string[];",
    "  readonly variants: readonly string[];",
    "  readonly prevents: string;",
    "  /** Keyed by heading: \"Rules\", \"Rules: variant\", \"Rules in the browser\", \"Rules in the browser: variant\". */",
    "  readonly rules: Readonly<Record<string, string>>;",
    "}",
    "",
    "export interface FrameData {",
    "  readonly opening: string;",
    "  readonly project: string;",
    "  readonly firstReplyCode: string;",
    "  readonly firstReplyAgent: string;",
    "  readonly firstReplyBrowser: string;",
    "}",
    "",
    `export const MODULES: readonly ModuleData[] = ${JSON.stringify(data.modules, null, 2)};`,
    "",
    `export const FRAME: FrameData = ${JSON.stringify(data.frame, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1]?.endsWith("build-modules.mjs")) {
  const rendered = renderModuleDataFile();
  if (process.argv.includes("--check")) {
    const current = (() => { try { return readFileSync(OUTPUT_PATH, "utf8"); } catch { return ""; } })();
    if (current !== rendered) {
      console.error("src/modules.data.ts is out of date. Run: npm run build:modules");
      process.exit(1);
    }
    console.log("src/modules.data.ts is up to date.");
  } else {
    writeFileSync(OUTPUT_PATH, rendered);
    console.log(`wrote src/modules.data.ts (${rendered.length} characters)`);
  }
}

export const UNUSED_MODULE_FILES = () =>
  readdirSync(MODULES_DIR).filter((name) => name.endsWith(".md") && !["README.md", "frame.md"].includes(name)
    && !MODULE_ORDER.includes(name.replace(/\.md$/, "")));
